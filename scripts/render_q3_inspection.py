"""Validate published Q3(c) aggregates and regenerate its table and statistics."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def wilson(success, n):
    z = 1.959963984540054
    rate = success / n
    center = (rate + z*z/(2*n)) / (1+z*z/n)
    half = z*math.sqrt(rate*(1-rate)/n+z*z/(4*n*n))/(1+z*z/n)
    return [center-half, center+half]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    data = json.loads((ROOT/'data/q3_inspection_20261107/summary.json').read_text())
    assert data['status'] == 'complete_audited' and not data['service_exclusions']
    assert data['raw_trials'] == 80 and data['seeds'] == [187301, 187302]
    groups = data['summary']
    for name in ('adaptive', 'fixed'):
        r = groups[name]
        assert r['raw_n'] == r['eligible_n'] == 40
        assert r['success'] == r['raw_success'] == r['reasons']['success']
        assert sum(r['reasons'].values()) == 40
        assert r['terminal_correct'] + r['terminal_wrong'] + r['unbound'] == 40
        assert sum(r['first_correct_call_histogram'].values()) + r['never_correct_binding'] == 40
        assert all(1 <= int(k) <= 6 for k in r['first_correct_call_histogram'])
        assert sum(r['drops_by_phase'].values()) == r['reasons'].get('drop', 0)
        assert set(r['per_seed']) == {'187301', '187302'}
        assert all(s['n'] == 20 for s in r['per_seed'].values())
        assert sum(s['success'] for s in r['per_seed'].values()) == r['success']
    pair = data['paired_success']
    a, f = pair['adaptive_only'], pair['fixed_only']
    both = groups['adaptive']['success'] - a
    neither = 40 - both - a - f
    assert both == groups['fixed']['success'] - f and min(a, f, both, neither) >= 0
    n = a + f
    exact = 1. if n == 0 else min(1., 2*sum(math.comb(n, i) for i in range(min(a, f)+1))/2**n)
    assert exact == pair['exact_two_sided_mcnemar_p']
    stats = dict(primary='Prespecified two-sided exact paired McNemar; one primary endpoint',
                 pairs=40, adaptive_only=a, fixed_only=f, both_success=both,
                 neither_success=neither, exact_p=exact,
                 success_difference_percentage_points=100*(a-f)/40,
                 wilson_95={name:wilson(r['success'], 40) for name,r in groups.items()},
                 interpretation='Observed advantage; does not reject equal success probability at alpha 0.05. No post-result sample extension.')
    lines = ['% Generated by scripts/render_q3_inspection.py; distinct Q3(c) cohort.',
             r'\newcommand{\InspectionPolicyRows}{%']
    for name,label in [('fixed','Fixed sweep'),('adaptive','Adaptive inspection')]:
        r = groups[name]
        lines.append(f"{label} & {r['success']}/40 & {r['success']/40*100:.1f} & {r['reasons'].get('drop',0)} & {r['calls']}" + r'\\')
    lines.append('}')
    outputs = {ROOT/'tables/q3_inspection_macros.tex':'\n'.join(lines)+'\n',
               ROOT/'data/q3_inspection_20261107/statistics.json':json.dumps(stats, indent=2)+'\n'}
    for path,text in outputs.items():
        if args.check:
            assert path.read_text() == text, f'Stale output: {path}'
        else:
            path.write_text(text)
    print(f'Q3(c): 40 pairs; gain {stats["success_difference_percentage_points"]:.1f} pp; exact p={exact:.8f}')


if __name__ == '__main__':
    main()
